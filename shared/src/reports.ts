import type { ImportedHistoryRef } from './api.js';
import { BRAND } from './brand.js';
import { contrastRatio } from './theme.js';
/** Archived PDF reports (run reports and periodic summaries) and their branding. */

export const REPORT_LANGS = ['en', 'de'] as const;
export type ReportLang = (typeof REPORT_LANGS)[number];

export type ReportKind = 'run' | 'summary' | 'scheduled';

/** A generated, stored and audited PDF. Records are immutable; every generation creates a new one. */
export interface ReportRecord {
  id: string;
  kind: ReportKind;
  /** Run reports: the run */
  runId?: string | null;
  /** Processes covered (run report: the run's process) */
  processIds: string[];
  /** Run reports: 1, 2, 3 … per run */
  version: number;
  title: string;
  lang: ReportLang;
  /** Reviewer comment entered when the report was generated */
  comment?: string | null;
  classification: string;
  /** Run report of a run that had not finished yet (waiting/interrupted) */
  interim: boolean;
  /** Generated automatically when the run finished (process option report.auto) */
  auto: boolean;
  createdBy: string;
  createdAt: string;
  filename: string;
  /** SHA-256 of the PDF file, also recorded in the audit log (report.generated) */
  sha256: string;
  size: number;
  /** Sealed fingerprint of the run journal at generation time (run reports) */
  protocolHash?: string | null;
  /** SHA-256 of the report's content model (embedded in the PDF metadata) */
  contentHash: string;
  /** Summary reports: covered period */
  from?: string | null;
  to?: string | null;
  /** Scheduled reports: the report schedule */
  scheduleId?: string | null;
}

export interface GenerateRunReportRequest {
  lang?: ReportLang;
  comment?: string;
  /** Overrides the default classification label from the branding settings */
  classification?: string;
  /** IANA time zone for the times shown in the report (default: server time zone) */
  timeZone?: string;
}

export interface GenerateSummaryReportRequest {
  processIds: string[];
  /** ISO timestamps (runs started in [from, to)) */
  from: string;
  to: string;
  lang?: ReportLang;
  comment?: string;
  classification?: string;
  timeZone?: string;
  title?: string;
}

/** Report branding (Settings → Report branding). */
export interface ReportBranding {
  /** Shown in the report header; empty = product name */
  companyName: string;
  /** Hex colour, e.g. #1c7ed6 */
  accentColor: string;
  /** Default classification label, e.g. "Internal" */
  classification: string;
  /** Printed in every page footer, e.g. "Confidential – for internal use only" */
  footerNote: string;
  /** A custom logo was uploaded (otherwise the Steward logo is used) */
  customLogo: boolean;
  logoMime?: string | null;
  logoUpdatedAt?: string | null;
}

export const REPORT_LOGO_MAX_BYTES = 1024 * 1024;

/** The report branding settings as shipped (Settings → Report branding → "Reset to default"). */
export const REPORT_BRANDING_DEFAULTS: Pick<ReportBranding, 'companyName' | 'accentColor' | 'classification' | 'footerNote'> = {
  companyName: '',
  accentColor: BRAND.color,
  classification: 'Internal',
  footerNote: '',
};

/** A readability note on the report accent colour (shown in Settings, like the theme's contrast notes). */
export interface ReportAccentNote {
  /** graphics: lines, bars and markers in the colour barely stand out from the white page (below 3:1) */
  kind: 'graphics';
  /** Contrast of the colour against the white page */
  ratio: number;
}

/** Non-text contrast (WCAG 1.4.11) the accent colour should reach against the white report page. */
export const REPORT_ACCENT_MIN_CONTRAST = 3;

/**
 * Reports use the accent colour for the header rule, section markers, chart bars and a light tint behind
 * table headers – never for text, which stays dark. So the colour must stand out from the white page as a
 * graphic (3:1); the tint keeps the dark text readable whatever the colour.
 */
export function reportAccentNotes(accentColor: string): ReportAccentNote[] {
  if (!/^#[0-9a-fA-F]{6}$/.test(accentColor)) return [];
  const ratio = contrastRatio(accentColor, '#ffffff');
  return ratio < REPORT_ACCENT_MIN_CONTRAST ? [{ kind: 'graphics', ratio }] : [];
}

/** Result of checking a PDF against the audit log (POST /api/reports/verify). */
export interface ReportVerification {
  /** exact: the file is a generated report; signed-copy: a generated report plus appended (signature) updates; unknown: not generated by this installation */
  match: 'exact' | 'signed-copy' | 'unknown';
  /** SHA-256 of the uploaded file */
  sha256: string;
  report?: {
    id: string;
    kind: string;
    runId?: string | null;
    filename?: string;
    sha256: string;
    size: number;
    generatedAt: string;
    generatedBy: string;
    auditSeq: number;
    /** The archived file is still stored (not removed by retention) */
    stored: boolean;
  };
  /** Result of verifying the whole audit chain */
  auditChain?: { ok: boolean; checked: number; message: string };
  /** Rows claiming to record this file that failed the HMAC/chain check (inserted outside the application) */
  forgedEntries?: number;
  /**
   * The report.generated entry is in audit history imported from another instance (docs/MIGRATION.md): the match is
   * verified against that history and the source's key, not this instance's own chain
   */
  importedHistory?: ImportedHistoryRef;
}

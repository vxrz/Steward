#!/usr/bin/env node
// Writes the translation keys of the web UI as TypeScript types (web/src/i18n/keys.gen.ts), or checks that the
// committed file is up to date (CI). See docs/I18N.md.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HELP = `Usage: npm run i18n:types -- [options]

Generates web/src/i18n/keys.gen.ts from the English translation files
(web/src/locales/en/<namespace>.json): per namespace, every key as a flat
"a.b.c" property. i18next.d.ts types t() with it, so a typo or a removed key
fails the typecheck – without TypeScript walking the nested JSON on every
call. npm run typecheck runs it first.

Options:
  --check         Compare with the file instead of writing it; exit 1 when it is outdated
  --root <dir>    Repository root (default: the folder above scripts/)
  -h, --help      Show this help

Exit codes: 0 success (or up to date), 1 outdated (--check), 2 usage or I/O error.`;

const OUT = 'web/src/i18n/keys.gen.ts';

/** "a.b.c" keys of a nested translation file, in file order. */
function flatKeys(obj, prefix = '', out = []) {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object' && !Array.isArray(v)) flatKeys(v, key, out);
    else out.push(key);
  }
  return out;
}

/** The generated source (formatted with the project's Prettier settings, so format:check agrees with it). */
export async function generate(root) {
  const dir = path.join(root, 'web/src/locales/en');
  const files = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort();
  const lines = [
    '// Generated by `npm run i18n:types` from web/src/locales/en/*.json – do not edit (CI checks it with --check).',
    '// The keys of each namespace, flat ("a.b.c"); i18next.d.ts types t() with them.',
    '',
    'export interface Resources {',
  ];
  for (const f of files) {
    const ns = f.slice(0, -'.json'.length);
    const keys = flatKeys(JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
    lines.push(`  ${JSON.stringify(ns)}: {`);
    for (const k of keys) lines.push(`    ${JSON.stringify(k)}: string;`);
    lines.push('  };');
  }
  lines.push('}', '');
  const prettier = await import('prettier');
  const file = path.join(root, OUT);
  const options = (await prettier.resolveConfig(file)) ?? {};
  return prettier.format(lines.join('\n'), { ...options, filepath: file });
}

async function main(argv) {
  let root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  let check = false;
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '-h' || a === '--help') {
      process.stdout.write(HELP + '\n');
      return 0;
    } else if (a === '--check') check = true;
    else if (a === '--root' && argv[i + 1]) root = path.resolve(argv[++i]);
    else {
      process.stderr.write(`i18n:types: unknown option "${a}"\n\n${HELP}\n`);
      return 2;
    }
  }
  const text = await generate(root);
  const file = path.join(root, OUT);
  if (check) {
    if (readIfExists(file) === text) {
      process.stdout.write(`✓ ${OUT} is up to date\n`);
      return 0;
    }
    process.stderr.write(`✗ ${OUT} is outdated – run npm run i18n:types\n`);
    return 1;
  }
  if (readIfExists(file) !== text) fs.writeFileSync(file, text);
  return 0;
}

/** The file's text, or '' when there is none (one read, no separate existence check that could race with it). */
function readIfExists(file) {
  try {
    return fs.readFileSync(file, 'utf8');
  } catch (e) {
    if (e && e.code === 'ENOENT') return '';
    throw e;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2)).then(
    (code) => process.exit(code),
    (e) => {
      process.stderr.write(`i18n:types: ${e instanceof Error ? e.message : String(e)}\n`);
      process.exit(2);
    },
  );
}

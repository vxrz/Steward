describe('SQL translation', () => {
  it('numbers ? placeholders outside literals, identifiers and comments', () => {
    expect(toPgPlaceholders('SELECT * FROM t WHERE a = ? AND b IN (?, ?)')).toBe('SELECT * FROM t WHERE a = $1 AND b IN ($2, $3)');
    expect(toPgPlaceholders("SELECT '?', 'it''s ?', \"we?ird\" FROM t WHERE x = ?")).toBe("SELECT '?', 'it''s ?', \"we?ird\" FROM t WHERE x = $1");
    expect(toPgPlaceholders('SELECT 1 -- what?\nFROM t /* why? */ WHERE a = ?')).toBe('SELECT 1 -- what?\nFROM t /* why? */ WHERE a = $1');
    expect(toPgPlaceholders('SELECT 1')).toBe('SELECT 1');
  });

  it('translates migration DDL', () => {
    expect(pgDdl('id INTEGER PRIMARY KEY AUTOINCREMENT,')).toBe('id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,');
    expect(pgDdl('seq INTEGER PRIMARY KEY,')).toBe('seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,');
    expect(pgDdl('size INTEGER NOT NULL, value REAL, data BLOB')).toBe('size BIGINT NOT NULL, value DOUBLE PRECISION, data BYTEA');
    expect(pgDdl("tags TEXT NOT NULL DEFAULT '[]'")).toBe(`tags TEXT COLLATE "C" NOT NULL DEFAULT '[]'`);
    expect(pgDdl('username TEXT NOT NULL UNIQUE COLLATE NOCASE,')).toBe('username TEXT COLLATE sm_nocase NOT NULL UNIQUE,');
    expect(pgDdl('ALTER TABLE x ADD COLUMN owner TEXT;')).toBe('ALTER TABLE x ADD COLUMN owner TEXT COLLATE "C";');
  });

  it('parses database targets and never shows passwords', () => {
    expect(parseDatabaseTarget('sqlite:/tmp/x.db')).toEqual({ kind: 'sqlite', file: '/tmp/x.db' });
    expect(parseDatabaseTarget('/tmp/x.db')).toEqual({ kind: 'sqlite', file: '/tmp/x.db' });
    expect(parseDatabaseTarget('postgres://u:pw@db:5432/sm', { schema: 'steward' })).toEqual({ kind: 'postgres', url: 'postgres://u:pw@db:5432/sm', schema: 'steward' });
    const withCa = parseDatabaseTarget('postgresql://u:pw@db/sm', { ca: '/etc/ca.pem' });
    expect(withCa.kind === 'postgres' && new URL(withCa.url).searchParams.get('sslrootcert')).toBe('/etc/ca.pem');
    expect(withCa.kind === 'postgres' && new URL(withCa.url).searchParams.get('sslmode')).toBe('verify-full');
    expect(() => parseDatabaseTarget('postgres://db/sm', { schema: 'bad-name;' })).toThrow(/schema/);
    expect(() => parseDatabaseTarget('mysql://u:pw@db/sm')).toThrow(/Unsupported/);
    expect(maskDatabaseUrl('postgres://user:s3cr%40t@db.corp:5432/sm?sslmode=require&password=x')).toBe('postgres://user@db.corp:5432/sm');
    expect(likeEscape('50%_a\\b')).toBe('50\\%\\_a\\\\b');
  });

  it('keeps server SQL portable (no SQLite-only constructs outside the database layer)', () => {
    const root = path.resolve(__dirname, '..', 'src');
    const files: string[] = [];
    const walk = (d: string) => {
      for (const e of fs.readdirSync(d, { withFileTypes: true })) {
        const p = path.join(d, e.name);
        if (e.isDirectory()) walk(p);
        else if (p.endsWith('.ts')) files.push(p);
      }
    };
    walk(root);
    const skip = (p: string) => p.includes(`${path.sep}database${path.sep}`) || p.endsWith(`${path.sep}db.ts`) || p.includes(`${path.sep}migrations${path.sep}`) || p.endsWith('db-copy.ts');
    const rules: [RegExp, string][] = [
      [/\bINSERT\s+OR\s+(IGNORE|REPLACE)\b/, 'use INSERT … ON CONFLICT … DO NOTHING / DO UPDATE'],
      [/\bPRAGMA\b/, 'PRAGMAs are SQLite-only (add a Db method)'],
      [/\b(julianday|strftime|group_concat|ifnull|iif|json_extract)\s*\(/i, 'SQLite-only SQL function (JSON: use db().jsonText)'],
      [/db\(\)\.raw\b|lastInsertRowid/, 'use the portable Db API (e.g. INSERT … RETURNING id with get())'],
      [/\bAS [a-z]+[A-Z]\w*/, 'quote camelCase aliases (AS "runId") – PostgreSQL folds unquoted names to lower case'],
    ];
    const problems: string[] = [];
    for (const f of files.filter((p) => !skip(p))) {
      fs.readFileSync(f, 'utf8')
        .split('\n')
        .forEach((line, i) => {
          if (/^\s*(\/\/|\*)/.test(line)) return;
          for (const [re, why] of rules) if (re.test(line)) problems.push(`${path.relative(root, f)}:${i + 1}: ${why}`);
          if (/\bLIKE\b/.test(line) && !/lower\(/.test(line)) problems.push(`${path.relative(root, f)}:${i + 1}: LIKE is case-sensitive on PostgreSQL – use lower(x) LIKE lower(?)`);
        });
    }
    expect(problems).toEqual([]);
  });
});

const ddl = (d: Db, sql: string) => (d.dialect === 'postgres' ? pgDdl(sql) : sql);

/** Behaviour both drivers must share. */
function sharedBehaviour(open: () => Db) {
  it('commits, rolls back and joins nested transactions', () => {
    const d = open();
    d.exec(ddl(d, 'CREATE TABLE t_tx (id INTEGER PRIMARY KEY, v TEXT NOT NULL)'));
    d.tx(() => d.run('INSERT INTO t_tx (id, v) VALUES (?, ?)', 1, 'a'));
    expect(() =>
      d.tx(() => {
        d.run('INSERT INTO t_tx (id, v) VALUES (?, ?)', 2, 'b');
        throw new Error('boom');
      }),
    ).toThrow('boom');
    expect(() =>
      d.tx(() => {
        d.run('INSERT INTO t_tx (id, v) VALUES (?, ?)', 3, 'c');
        d.tx(() => {
          d.run('INSERT INTO t_tx (id, v) VALUES (?, ?)', 4, 'd');
          throw new Error('inner');
        });
      }),
    ).toThrow('inner');
    // a failing statement inside a transaction rolls it back; the connection stays usable
    expect(() =>
      d.tx(() => {
        d.run('INSERT INTO t_tx (id, v) VALUES (?, ?)', 5, 'e');
        d.run('INSERT INTO t_tx (id, v) VALUES (?, ?)', 1, 'duplicate');
      }),
    ).toThrow();
    expect(d.all<{ id: number }>('SELECT id FROM t_tx ORDER BY id').map((r) => r.id)).toEqual([1]);
    expect(d.inTransaction).toBe(false);
    expect(d.run('UPDATE t_tx SET v = ? WHERE id > ?', 'z', 0).changes).toBe(1);
  });

  it('returns numbers for integers and counts, and Uint8Array for binary data', () => {
    const d = open();
    d.exec(ddl(d, 'CREATE TABLE t_types (id INTEGER PRIMARY KEY, big INTEGER, r REAL, data BLOB, s TEXT)'));
    const bytes = new Uint8Array([0, 1, 2, 250, 255]);
    d.run('INSERT INTO t_types (id, big, r, data, s) VALUES (?, ?, ?, ?, ?)', 1, 9_000_000_000, 1.5, Buffer.from(bytes), 'x?');
    d.run('INSERT INTO t_types (id, big, r, data, s) VALUES (?, ?, ?, ?, ?)', 2, null, null, bytes, null);
    const rows = d.all<{ id: number; big: number | null; r: number | null; data: Uint8Array; s: string | null }>('SELECT * FROM t_types ORDER BY id');
    expect(rows[0]).toMatchObject({ id: 1, big: 9_000_000_000, r: 1.5, s: 'x?' });
    expect(rows[0]!.data).toBeInstanceOf(Uint8Array);
    expect([...rows[0]!.data]).toEqual([...bytes]);
    expect([...rows[1]!.data]).toEqual([...bytes]);
    expect(rows[1]).toMatchObject({ big: null, r: null, s: null });
    expect(d.get('SELECT COUNT(*) AS n, MAX(big) AS m FROM t_types')).toEqual({ n: 2, m: 9_000_000_000 });
    expect(d.get<{ q: string }>("SELECT '?' AS q WHERE 1 = ?", 1)?.q).toBe('?');
  });

  it('compares user and team names case-insensitively', () => {
    const d = open();
    const ts = new Date().toISOString();
    d.run("INSERT INTO users (id, username, display_name, password_hash, created_at, updated_at) VALUES ('u1', 'Alice', 'A', 'x', ?, ?)", ts, ts);
    expect(d.get<{ id: string }>('SELECT id FROM users WHERE username = ?', 'aLiCe')?.id).toBe('u1');
    expect(() => d.run("INSERT INTO users (id, username, display_name, password_hash, created_at, updated_at) VALUES ('u2', 'ALICE', 'A', 'x', ?, ?)", ts, ts)).toThrow();
    // other text sorts byte-wise, like SQLite
    d.run("INSERT INTO settings (key, value) VALUES ('b', '1'), ('B', '2'), ('a', '3')");
    expect(d.all<{ key: string }>('SELECT key FROM settings ORDER BY key').map((r) => r.key)).toEqual(['B', 'a', 'b']);
  });
}

describe('SQLite driver', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'sm-db-'));
  const opened: Db[] = [];
  let n = 0;
  const open = () => {
    const d = new Db({ kind: 'sqlite', file: path.join(dir, `t${n++}.db`) });
    opened.push(d);
    return d;
  };
  afterAll(() => {
    for (const d of opened) d.close();
    fs.rmSync(dir, { recursive: true, force: true });
  });
  sharedBehaviour(open);
});

describe.skipIf(!PG_TEST_URL)('PostgreSQL driver (sync bridge)', () => {
  const prefix = process.env.SM_TEST_SCHEMA_PREFIX ?? 'smt_adhoc';
  let n = 0;
  const opened: Db[] = [];
  const schemaName = () => `${prefix}_db${process.pid}_${n++}`;
  const target = (schema: string): Extract<DatabaseTarget, { kind: 'postgres' }> => ({ kind: 'postgres', url: PG_TEST_URL!, schema });
  const open = (schema = schemaName(), extra: Partial<PgBridgeOptions> = {}, migrate = true) => {
    const d = new Db(new PostgresDriver(target(schema), extra), { migrate });
    opened.push(d);
    return d;
  };
  afterAll(() => {
    for (const d of opened) d.close();
  });

  sharedBehaviour(() => open());

  it('surfaces PostgreSQL errors with message and SQLSTATE', () => {
    const d = open(schemaName(), {}, false);
    let err: (Error & { code?: string; constraint?: string }) | undefined;
    try {
      d.get('SELEC 1');
    } catch (e) {
      err = e as Error;
    }
    expect(err).toBeInstanceOf(Error);
    expect(err!.message).toMatch(/syntax error/);
    expect(err!.code).toBe('42601');
    d.exec('CREATE TABLE u (k TEXT PRIMARY KEY)');
    d.run('INSERT INTO u (k) VALUES (?)', 'a');
    try {
      d.run('INSERT INTO u (k) VALUES (?)', 'a');
    } catch (e) {
      err = e as Error;
    }
    expect(err!.code).toBe('23505');
    expect(err!.constraint).toBe('u_pkey');
    expect(d.get('SELECT 1 AS one')).toEqual({ one: 1 });
  });

  it('cancels slow statements server-side and recovers from a stuck connection', () => {
    const d = open(schemaName(), { timeoutMs: 1500 }, false);
    expect(() => d.get('SELECT pg_sleep(3)')).toThrow(expect.objectContaining({ code: '57014' })); // statement_timeout
    expect(d.get('SELECT 2 AS two')).toEqual({ two: 2 });

    const stuck = open(schemaName(), { timeoutMs: 1000, statementTimeoutMs: 0 }, false);
    const t0 = Date.now();
    expect(() => stuck.get('SELECT pg_sleep(2)')).toThrow(expect.objectContaining({ code: 'SM_DB_TIMEOUT' }));
    expect(Date.now() - t0).toBeLessThan(1900);
    // a fresh connection is opened (re-taking the instance lock once the old session is gone)
    expect(stuck.get('SELECT 3 AS three')).toEqual({ three: 3 });
    // a timeout inside a transaction aborts the whole transaction
    stuck.exec('CREATE TABLE tt (id INTEGER)');
    expect(() =>
      stuck.tx(() => {
        stuck.run('INSERT INTO tt (id) VALUES (1)');
        stuck.get('SELECT pg_sleep(2)');
      }),
    ).toThrow(/did not answer/);
    expect(stuck.get('SELECT COUNT(*) AS n FROM tt')).toEqual({ n: 0 });
  }, 30000);

  it('allows only one app instance per schema', () => {
    const schema = schemaName();
    const first = open(schema);
    expect(() => open(schema, { lockWaitMs: 300 })).toThrow(/Another .* instance is already using this database schema/);
    first.close();
    expect(open(schema).get('SELECT version FROM schema_version')).toEqual({ version: coreMigrations('postgres').length });
  });

  it('creates the same tables and columns as on SQLite', () => {
    const lite = new Db({ kind: 'sqlite', file: ':memory:' });
    const pg = open();
    const liteTables = lite.all<{ name: string }>("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite\\_%' ESCAPE '\\' ORDER BY name").map((r) => r.name);
    const pgTables = pg
      .all<{ name: string }>("SELECT table_name AS name FROM information_schema.tables WHERE table_schema = current_schema() ORDER BY table_name")
      .map((r) => r.name);
    expect(pgTables).toEqual(liteTables);
    const typeMap: Record<string, string> = { INTEGER: 'bigint', TEXT: 'text', REAL: 'double precision', BLOB: 'bytea' };
    for (const t of liteTables) {
      const lc = lite.all<{ name: string; type: string; notnull: number }>('SELECT name, type, "notnull" FROM pragma_table_info(?) ORDER BY cid', t);
      const pc = pg
        .all<{ name: string; type: string; notnull: number }>(
          "SELECT column_name AS name, data_type AS type, CASE WHEN is_nullable = 'NO' THEN 1 ELSE 0 END AS notnull FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = ? AND column_name <> 'rowid' ORDER BY ordinal_position",
          t,
        )
        .filter((c) => !(t.startsWith('schema_') && c.name === 'version'));
      const expected = lc.filter((c) => !(t.startsWith('schema_') && c.name === 'version')).map((c) => [c.name, typeMap[c.type] ?? c.type, c.notnull]);
      // (SQLite does not mark INTEGER PRIMARY KEY columns NOT NULL; PostgreSQL does)
      const pk = new Set(lite.all<{ name: string }>('SELECT name FROM pragma_table_info(?) WHERE pk > 0', t).map((r) => r.name));
      expect(
        pc.map((c) => [c.name, c.type, pk.has(c.name) ? 0 : c.notnull]),
        t,
      ).toEqual(expected.map(([name, type, nn]) => [name, type, pk.has(name as string) ? 0 : nn]));
    }
    expect(namedMigrations('postgres').map((m) => m.name)).toEqual(namedMigrations('sqlite').map((m) => m.name));
    lite.close();
  });
});

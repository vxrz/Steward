/**
 * Small, explicit SQL helpers for running the app's SQLite-flavoured SQL on PostgreSQL.
 * Call sites are written in portable SQL; only two mechanical translations happen here:
 *   - `?` placeholders → `$1..$n` (every query)
 *   - SQLite DDL → PostgreSQL DDL (migrations only)
 */

/**
 * Replaces `?` placeholders with `$1..$n`, leaving `?` inside string literals,
 * quoted identifiers and comments alone.
 */
export function toPgPlaceholders(sql: string): string {
  let out = '';
  let n = 0;
  let i = 0;
  const len = sql.length;
  while (i < len) {
    const c = sql[i]!;
    if (c === "'" || c === '"') {
      // string literal / quoted identifier; a doubled quote is an escaped quote
      let j = i + 1;
      for (;;) {
        if (j >= len) break;
        if (sql[j] === c) {
          if (sql[j + 1] === c) j += 2;
          else break;
        } else j++;
      }
      out += sql.slice(i, j + 1);
      i = j + 1;
    } else if (c === '-' && sql[i + 1] === '-') {
      const j = sql.indexOf('\n', i);
      const end = j < 0 ? len : j;
      out += sql.slice(i, end);
      i = end;
    } else if (c === '/' && sql[i + 1] === '*') {
      const j = sql.indexOf('*/', i + 2);
      const end = j < 0 ? len : j + 2;
      out += sql.slice(i, end);
      i = end;
    } else if (c === '?') {
      out += '$' + ++n;
      i++;
    } else {
      out += c;
      i++;
    }
  }
  return out;
}

/** Case-insensitive collation used for SQLite's `COLLATE NOCASE` columns (user and team names). */
export const PG_NOCASE_COLLATION = 'sm_nocase';
export const PG_CREATE_NOCASE = `CREATE COLLATION IF NOT EXISTS ${PG_NOCASE_COLLATION} (provider = icu, locale = 'und-u-ks-level2', deterministic = false)`;

/**
 * Translates the SQLite DDL used by the migrations to PostgreSQL:
 *   - `INTEGER PRIMARY KEY [AUTOINCREMENT]` → identity column (explicit values are still allowed)
 *   - `INTEGER` → `BIGINT` (SQLite integers are 64 bit), `REAL` → `DOUBLE PRECISION`, `BLOB` → `BYTEA`
 *   - `TEXT` → `TEXT COLLATE "C"` (byte-order comparison and sorting like SQLite's BINARY),
 *     `TEXT … COLLATE NOCASE` → case-insensitive ICU collation
 * Keywords are matched in upper case only, as the migrations write them.
 */
export function pgDdl(sql: string): string {
  return sql
    .replace(/\bINTEGER PRIMARY KEY( AUTOINCREMENT)?\b/g, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\b/g, 'BIGINT')
    .replace(/\bREAL\b/g, 'DOUBLE PRECISION')
    .replace(/\bBLOB\b/g, 'BYTEA')
    .replace(/\bTEXT\b((?:\s+(?:NOT NULL|UNIQUE|PRIMARY KEY))*)\s+COLLATE NOCASE\b/g, `TEXT COLLATE ${PG_NOCASE_COLLATION}$1`)
    .replace(/\bTEXT\b(?!\s+COLLATE)/g, 'TEXT COLLATE "C"');
}

export const quoteIdent = (name: string): string => '"' + name.replace(/"/g, '""') + '"';

/** Escapes `%`, `_` and `\` for a `LIKE … ESCAPE '\'` pattern. */
export const likeEscape = (s: string): string => s.replace(/[\\%_]/g, '\\$&');

/** postgres://user:secret@host:5432/db?… → postgres://user@host:5432/db (never log passwords). */
export function maskDatabaseUrl(url: string): string {
  try {
    const u = new URL(url);
    const user = u.username ? decodeURIComponent(u.username) + '@' : '';
    return `${u.protocol}//${user}${u.host}${u.pathname}`;
  } catch {
    return 'postgres://(invalid URL)';
  }
}

export type DatabaseTarget =
  | { kind: 'sqlite'; file: string }
  | {
      kind: 'postgres';
      url: string;
      /** Schema for all tables (created if missing). Default `public`. */
      schema: string;
      /** Hold a session advisory lock so only one app instance uses this schema (default true). */
      lock?: boolean;
      /** Longest wait for one statement before the call fails (ms, default 30000). */
      timeoutMs?: number;
    };

const SCHEMA_RE = /^[A-Za-z_][A-Za-z0-9_]{0,62}$/;

/**
 * Database target from a spec string: `postgres://…` / `postgresql://…`, `sqlite:<file>` or a file path.
 * `ca` (path to a CA certificate) is added as `sslrootcert` (with `sslmode=verify-full` unless set).
 */
export function parseDatabaseTarget(spec: string, opts: { schema?: string; ca?: string } = {}): DatabaseTarget {
  if (/^postgres(ql)?:\/\//i.test(spec)) {
    const schema = opts.schema || 'public';
    if (!SCHEMA_RE.test(schema)) throw new Error(`Invalid database schema name "${schema}" (letters, digits and _ only)`);
    let url = spec;
    if (opts.ca) {
      const u = new URL(spec);
      if (!u.searchParams.has('sslrootcert')) u.searchParams.set('sslrootcert', opts.ca);
      if (!u.searchParams.has('sslmode')) u.searchParams.set('sslmode', 'verify-full');
      url = u.toString();
    }
    return { kind: 'postgres', url, schema };
  }
  if (/^[a-z][a-z0-9+.-]*:\/\//i.test(spec)) throw new Error(`Unsupported database URL "${maskDatabaseUrl(spec)}" – use postgres://user:password@host:5432/database`);
  const file = spec.startsWith('sqlite:') ? spec.slice('sqlite:'.length) : spec;
  if (!file) throw new Error('Missing SQLite file path');
  return { kind: 'sqlite', file };
}

export function describeTarget(t: DatabaseTarget): string {
  return t.kind === 'sqlite' ? `sqlite:${t.file}` : maskDatabaseUrl(t.url) + (t.schema !== 'public' ? ` (schema ${t.schema})` : '');
}

/**
 * The schema read of a database platform (#222): Steward's own catalog statements, like those of catalog.ts – tables
 * and views, columns (type, null, default, comment), primary and foreign keys, unique keys and indexes – read in the
 * same read-only (or always rolled back) transaction as every statement, one statement per part, each within a row
 * limit. MariaDB/MySQL statements read one information_schema view each (joins across those views can meet different
 * collations); nothing here is recursive. The statements take no parameters and no text from outside.
 */

export const SCHEMA_PARTS = ['tables', 'columns', 'keys', 'references', 'indexes'] as const;
export type SchemaPart = (typeof SCHEMA_PARTS)[number];

/** Rows a part may return; a part with more is cut there and the snapshot marked truncated. */
export const SCHEMA_PART_ROWS: Record<SchemaPart, number> = {
  tables: DB_SCHEMA_LIMITS.tables,
  columns: DB_SCHEMA_LIMITS.columns,
  keys: DB_SCHEMA_LIMITS.columns,
  references: DB_SCHEMA_LIMITS.columns,
  indexes: DB_SCHEMA_LIMITS.columns,
};
/** Size of one part's result (bytes, as JSON) */
export const SCHEMA_PART_BYTES = 32 * 1024 * 1024;

const PG_NS = `n.nspname NOT IN ('pg_catalog', 'information_schema') AND n.nspname NOT LIKE 'pg!_toast%' ESCAPE '!' AND n.nspname NOT LIKE 'pg!_temp!_%' ESCAPE '!'`;
const PG_REL = `c.relkind IN ('r', 'p', 'v', 'm', 'f') AND NOT c.relispartition`;
/** The columns of a key in key order, by attribute numbers (conkey, confkey, indkey). */
const pgCols = (rel: string, keys: string, upTo = '') =>
  `ARRAY(SELECT a.attname::text FROM unnest(${keys}) WITH ORDINALITY k(attnum, ord) JOIN pg_attribute a ON a.attrelid = ${rel} AND a.attnum = k.attnum${upTo} ORDER BY k.ord)::text[]`;

const POSTGRES: Record<SchemaPart, string> = {
  tables: `SELECT n.nspname AS schema_name, c.relname AS table_name,
  CASE c.relkind WHEN 'v' THEN 'view' WHEN 'm' THEN 'materialized view' WHEN 'f' THEN 'foreign table' ELSE 'table' END AS table_type,
  obj_description(c.oid, 'pg_class') AS comment
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE ${PG_REL} AND ${PG_NS}
ORDER BY 1, 2`,
  columns: `SELECT n.nspname AS schema_name, c.relname AS table_name, a.attname AS column_name, a.attnum AS position,
  format_type(a.atttypid, a.atttypmod) AS data_type, NOT a.attnotnull AS nullable,
  CASE WHEN a.attidentity = 'a' THEN 'GENERATED ALWAYS AS IDENTITY' WHEN a.attidentity = 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY'
    WHEN a.attgenerated = 's' THEN 'GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
    ELSE pg_get_expr(d.adbin, d.adrelid) END AS column_default,
  col_description(c.oid, a.attnum) AS comment
FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid JOIN pg_namespace n ON n.oid = c.relnamespace
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE a.attnum > 0 AND NOT a.attisdropped AND ${PG_REL} AND ${PG_NS}
ORDER BY 1, 2, 4`,
  keys: `SELECT n.nspname AS schema_name, c.relname AS table_name, con.conname AS constraint_name,
  CASE con.contype WHEN 'p' THEN 'PRIMARY KEY' ELSE 'UNIQUE' END AS constraint_type, ${pgCols('con.conrelid', 'con.conkey')} AS columns
FROM pg_constraint con JOIN pg_class c ON c.oid = con.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE con.contype IN ('p', 'u') AND ${PG_REL} AND ${PG_NS}
ORDER BY 1, 2, 3`,
  references: `SELECT n.nspname AS schema_name, c.relname AS table_name, con.conname AS constraint_name, ${pgCols('con.conrelid', 'con.conkey')} AS columns,
  fn.nspname AS ref_schema, fc.relname AS ref_table, ${pgCols('con.confrelid', 'con.confkey')} AS ref_columns,
  CASE con.confupdtype WHEN 'c' THEN 'CASCADE' WHEN 'r' THEN 'RESTRICT' WHEN 'n' THEN 'SET NULL' WHEN 'd' THEN 'SET DEFAULT' ELSE 'NO ACTION' END AS on_update,
  CASE con.confdeltype WHEN 'c' THEN 'CASCADE' WHEN 'r' THEN 'RESTRICT' WHEN 'n' THEN 'SET NULL' WHEN 'd' THEN 'SET DEFAULT' ELSE 'NO ACTION' END AS on_delete
FROM pg_constraint con JOIN pg_class c ON c.oid = con.conrelid JOIN pg_namespace n ON n.oid = c.relnamespace
JOIN pg_class fc ON fc.oid = con.confrelid JOIN pg_namespace fn ON fn.oid = fc.relnamespace
WHERE con.contype = 'f' AND ${PG_REL} AND ${PG_NS}
ORDER BY 1, 2, 3`,
  indexes: `SELECT n.nspname AS schema_name, c.relname AS table_name, i.relname AS index_name, x.indisunique AS is_unique, x.indisprimary AS is_primary,
  ${pgCols('x.indrelid', 'x.indkey::int2[]', ' AND k.ord <= x.indnkeyatts')} AS columns, pg_get_indexdef(x.indexrelid) AS definition
FROM pg_index x JOIN pg_class i ON i.oid = x.indexrelid JOIN pg_class c ON c.oid = x.indrelid JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE ${PG_REL} AND ${PG_NS}
ORDER BY 1, 2, 3`,
};

/** MariaDB and MySQL: the database of the connection (DATABASE()), one information_schema view per statement. */
const MYSQL: Record<SchemaPart, string> = {
  tables: `SELECT TABLE_SCHEMA AS schema_name, TABLE_NAME AS table_name, TABLE_TYPE AS table_type, TABLE_COMMENT AS comment
FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_TYPE <> 'SEQUENCE'
ORDER BY TABLE_NAME`,
  columns: `SELECT TABLE_SCHEMA AS schema_name, TABLE_NAME AS table_name, COLUMN_NAME AS column_name, ORDINAL_POSITION AS position,
  COLUMN_TYPE AS data_type, IS_NULLABLE AS nullable, COLUMN_DEFAULT AS column_default, EXTRA AS extra, GENERATION_EXPRESSION AS generation,
  COLUMN_COMMENT AS comment
FROM information_schema.COLUMNS WHERE TABLE_SCHEMA = DATABASE()
ORDER BY TABLE_NAME, ORDINAL_POSITION`,
  // primary, unique and foreign keys in one view (as tbls reads them): a referenced table makes a foreign key
  keys: `SELECT TABLE_SCHEMA AS schema_name, TABLE_NAME AS table_name, CONSTRAINT_NAME AS constraint_name, COLUMN_NAME AS column_name,
  ORDINAL_POSITION AS position, REFERENCED_TABLE_SCHEMA AS ref_schema, REFERENCED_TABLE_NAME AS ref_table, REFERENCED_COLUMN_NAME AS ref_column
FROM information_schema.KEY_COLUMN_USAGE WHERE TABLE_SCHEMA = DATABASE()
ORDER BY TABLE_NAME, CONSTRAINT_NAME, ORDINAL_POSITION`,
  references: `SELECT TABLE_NAME AS table_name, CONSTRAINT_NAME AS constraint_name, UPDATE_RULE AS on_update, DELETE_RULE AS on_delete
FROM information_schema.REFERENTIAL_CONSTRAINTS WHERE CONSTRAINT_SCHEMA = DATABASE()
ORDER BY TABLE_NAME, CONSTRAINT_NAME`,
  indexes: `SELECT TABLE_SCHEMA AS schema_name, TABLE_NAME AS table_name, INDEX_NAME AS index_name, NON_UNIQUE AS non_unique, SEQ_IN_INDEX AS position,
  COLUMN_NAME AS column_name, INDEX_TYPE AS index_type
FROM information_schema.STATISTICS WHERE TABLE_SCHEMA = DATABASE()
ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX`,
};

/** SQL Server: the database of the connection; descriptions are the MS_Description extended properties. */
const SQLSERVER: Record<SchemaPart, string> = {
  tables: `SELECT s.name AS schema_name, o.name AS table_name, CASE o.type WHEN 'V' THEN 'view' ELSE 'table' END AS table_type,
  CAST(ep.value AS nvarchar(4000)) AS comment
FROM sys.objects o JOIN sys.schemas s ON s.schema_id = o.schema_id
LEFT JOIN sys.extended_properties ep ON ep.class = 1 AND ep.major_id = o.object_id AND ep.minor_id = 0 AND ep.name = N'MS_Description'
WHERE o.type IN ('U', 'V') AND o.is_ms_shipped = 0
ORDER BY s.name, o.name`,
  columns: `SELECT s.name AS schema_name, o.name AS table_name, c.name AS column_name, c.column_id AS position, t.name AS type_name,
  c.max_length AS max_length, c.precision AS num_precision, c.scale AS num_scale, c.is_nullable AS nullable, c.is_identity AS is_identity,
  dc.definition AS column_default, cc.definition AS computed, CAST(ep.value AS nvarchar(4000)) AS comment
FROM sys.columns c JOIN sys.objects o ON o.object_id = c.object_id JOIN sys.schemas s ON s.schema_id = o.schema_id
JOIN sys.types t ON t.user_type_id = c.user_type_id
LEFT JOIN sys.default_constraints dc ON dc.object_id = c.default_object_id
LEFT JOIN sys.computed_columns cc ON cc.object_id = c.object_id AND cc.column_id = c.column_id
LEFT JOIN sys.extended_properties ep ON ep.class = 1 AND ep.major_id = c.object_id AND ep.minor_id = c.column_id AND ep.name = N'MS_Description'
WHERE o.type IN ('U', 'V') AND o.is_ms_shipped = 0
ORDER BY s.name, o.name, c.column_id`,
  keys: `SELECT s.name AS schema_name, t.name AS table_name, kc.name AS constraint_name, CASE kc.type WHEN 'PK' THEN 'PRIMARY KEY' ELSE 'UNIQUE' END AS constraint_type,
  c.name AS column_name, ic.key_ordinal AS position
FROM sys.key_constraints kc JOIN sys.tables t ON t.object_id = kc.parent_object_id JOIN sys.schemas s ON s.schema_id = t.schema_id
JOIN sys.index_columns ic ON ic.object_id = kc.parent_object_id AND ic.index_id = kc.unique_index_id
JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id
WHERE t.is_ms_shipped = 0 AND ic.key_ordinal > 0
ORDER BY s.name, t.name, kc.name, ic.key_ordinal`,
  references: `SELECT s.name AS schema_name, t.name AS table_name, fk.name AS constraint_name, pc.name AS column_name, fkc.constraint_column_id AS position,
  rs.name AS ref_schema, rt.name AS ref_table, rc.name AS ref_column,
  fk.update_referential_action_desc AS on_update, fk.delete_referential_action_desc AS on_delete
FROM sys.foreign_keys fk JOIN sys.tables t ON t.object_id = fk.parent_object_id JOIN sys.schemas s ON s.schema_id = t.schema_id
JOIN sys.foreign_key_columns fkc ON fkc.constraint_object_id = fk.object_id
JOIN sys.columns pc ON pc.object_id = fkc.parent_object_id AND pc.column_id = fkc.parent_column_id
JOIN sys.tables rt ON rt.object_id = fk.referenced_object_id JOIN sys.schemas rs ON rs.schema_id = rt.schema_id
JOIN sys.columns rc ON rc.object_id = fkc.referenced_object_id AND rc.column_id = fkc.referenced_column_id
WHERE t.is_ms_shipped = 0
ORDER BY s.name, t.name, fk.name, fkc.constraint_column_id`,
  indexes: `SELECT s.name AS schema_name, o.name AS table_name, i.name AS index_name, i.is_unique AS is_unique, i.is_primary_key AS is_primary,
  i.type_desc AS index_type, c.name AS column_name, ic.key_ordinal AS position
FROM sys.indexes i JOIN sys.objects o ON o.object_id = i.object_id JOIN sys.schemas s ON s.schema_id = o.schema_id
JOIN sys.index_columns ic ON ic.object_id = i.object_id AND ic.index_id = i.index_id
JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id
WHERE o.type IN ('U', 'V') AND o.is_ms_shipped = 0 AND i.index_id > 0 AND i.is_hypothetical = 0 AND ic.key_ordinal > 0 AND i.name IS NOT NULL
ORDER BY s.name, o.name, i.name, ic.key_ordinal`,
};

export const SCHEMA_SQL: Record<Flavour, Record<SchemaPart, string>> = { postgresql: POSTGRES, mysql: MYSQL, mariadb: MYSQL, sqlserver: SQLSERVER };

export const schemaSql = (part: SchemaPart, server: { flavour: Flavour }): string => SCHEMA_SQL[server.flavour][part];

// ---------- rows → schema ----------

type Row = Record<string, unknown>;
const text = (v: unknown): string | null => (v === null || v === undefined ? null : String(v));
const yes = (v: unknown): boolean => v === true || v === 1 || v === '1' || (typeof v === 'string' && /^(yes|y|t|true)$/i.test(v));
/** A text[] from pg (an array, or "{a,b}" when the driver did not parse it). */
const arr = (v: unknown): string[] => {
  if (Array.isArray(v)) return v.map(String);
  if (typeof v !== 'string' || !v.startsWith('{')) return [];
  return v
    .slice(1, -1)
    .split(',')
    .map((x) => x.trim().replace(/^"|"$/g, ''))
    .filter(Boolean);
};

/** SQL Server: the data type as it is declared (nvarchar(120), decimal(10,2), datetime2(3), varchar(max)). */
export function mssqlType(r: Row): string {
  const t = String(r.type_name ?? '');
  const len = Number(r.max_length);
  const lower = t.toLowerCase();
  if (['varchar', 'char', 'varbinary', 'binary'].includes(lower)) return `${t}(${len === -1 ? 'max' : len})`;
  if (['nvarchar', 'nchar'].includes(lower)) return `${t}(${len === -1 ? 'max' : len / 2})`;
  if (['decimal', 'numeric'].includes(lower)) return `${t}(${Number(r.num_precision)},${Number(r.num_scale)})`;
  if (['datetime2', 'time', 'datetimeoffset'].includes(lower)) return `${t}(${Number(r.num_scale)})`;
  return t;
}

/** SQL Server writes defaults in brackets: ((0)), (getdate()), ('open'). */
const mssqlDefault = (v: unknown): string | null => {
  let s = text(v);
  if (s === null) return null;
  while (s.startsWith('(') && s.endsWith(')') && balanced(s.slice(1, -1))) s = s.slice(1, -1);
  return s;
};
function balanced(s: string): boolean {
  let depth = 0;
  let quoted = false;
  for (const ch of s) {
    if (ch === "'") quoted = !quoted;
    else if (!quoted && ch === '(') depth++;
    else if (!quoted && ch === ')' && --depth < 0) return false;
  }
  return depth === 0 && !quoted;
}

/** MariaDB writes literal defaults quoted and DEFAULT NULL as the word NULL; MySQL neither. */
const myDefault = (v: unknown, extra: string, generation: unknown): string | null => {
  const s = text(v);
  if (/auto_increment/i.test(extra)) return 'AUTO_INCREMENT';
  const gen = /\b(VIRTUAL|STORED|PERSISTENT) GENERATED\b/i.exec(extra);
  if (gen && text(generation)) return `GENERATED ALWAYS AS (${text(generation)}) ${gen[1]!.toUpperCase() === 'VIRTUAL' ? 'VIRTUAL' : 'STORED'}`;
  if (s === null || s.toUpperCase() === 'NULL') return null;
  return s;
};

/** The rows of the parts, assembled into tables. `truncated` marks a part that reached its row limit. */
export function assembleSchema(
  flavour: Flavour,
  parts: Record<SchemaPart, { rows: Row[]; truncated: boolean }>,
  ctx: { database: string; version: string },
): DbSchemaDoc {
  const tables = new Map<string, TableInput & { columns: NonNullable<TableInput['columns']> }>();
  const key = (schema: unknown, name: unknown) => `${text(schema) ?? ''}\u0000${text(name) ?? ''}`;
  for (const r of parts.tables.rows) {
    const type = String(r.table_type ?? 'table')
      .toLowerCase()
      .replace(/^base table$/, 'table')
      .replace(/^system versioned$/, 'table');
    let comment = text(r.comment);
    // MySQL writes "VIEW" as the comment of a view
    if (comment === '' || (type === 'view' && comment === 'VIEW')) comment = null;
    tables.set(key(r.schema_name, r.table_name), {
      schema: text(r.schema_name),
      name: String(r.table_name ?? ''),
      type,
      comment,
      columns: [],
      foreignKeys: [],
      indexes: [],
    });
  }
  for (const r of parts.columns.rows) {
    const t = tables.get(key(r.schema_name, r.table_name));
    if (!t) continue; // a table beyond the table limit
    let type: string;
    let dflt: string | null;
    let nullable: boolean;
    if (flavour === 'sqlserver') {
      type = mssqlType(r);
      dflt = yes(r.is_identity)
        ? 'IDENTITY'
        : r.computed !== null && r.computed !== undefined
          ? `GENERATED ALWAYS AS ${String(r.computed)}`
          : mssqlDefault(r.column_default);
      nullable = yes(r.nullable);
    } else if (flavour === 'postgresql') {
      type = String(r.data_type ?? '');
      dflt = text(r.column_default);
      nullable = yes(r.nullable);
    } else {
      type = String(r.data_type ?? '');
      dflt = myDefault(r.column_default, String(r.extra ?? ''), r.generation);
      nullable = String(r.nullable ?? '').toUpperCase() === 'YES';
    }
    const comment = text(r.comment);
    t.columns.push({ name: String(r.column_name ?? ''), type, nullable, default: dflt, comment: comment === '' ? null : comment });
  }
  // keys
  if (flavour === 'postgresql') {
    for (const r of parts.keys.rows) {
      const t = tables.get(key(r.schema_name, r.table_name));
      if (!t) continue;
      if (r.constraint_type === 'PRIMARY KEY') t.primaryKey = { name: text(r.constraint_name), columns: arr(r.columns) };
    }
    for (const r of parts.references.rows) {
      const t = tables.get(key(r.schema_name, r.table_name));
      if (!t) continue;
      t.foreignKeys!.push({
        name: text(r.constraint_name),
        columns: arr(r.columns),
        refSchema: text(r.ref_schema),
        refTable: String(r.ref_table ?? ''),
        refColumns: arr(r.ref_columns),
        onUpdate: text(r.on_update),
        onDelete: text(r.on_delete),
      });
    }
    for (const r of parts.indexes.rows) {
      const t = tables.get(key(r.schema_name, r.table_name));
      if (!t) continue;
      t.indexes!.push({
        name: String(r.index_name ?? ''),
        columns: arr(r.columns),
        unique: yes(r.is_unique),
        primary: yes(r.is_primary),
        definition: text(r.definition),
      });
    }
  } else {
    // one row per key column: grouped by table and constraint
    const rules = new Map<string, { onUpdate: string | null; onDelete: string | null }>();
    for (const r of parts.references.rows)
      if (flavour !== 'sqlserver')
        rules.set(`${text(r.table_name)}\u0000${text(r.constraint_name)}`, { onUpdate: text(r.on_update), onDelete: text(r.on_delete) });
    const groups = new Map<
      string,
      {
        t: TableInput;
        name: string;
        kind: string;
        cols: string[];
        refSchema: string | null;
        refTable: string | null;
        refCols: string[];
        rule?: { onUpdate: string | null; onDelete: string | null };
      }
    >();
    const add = (r: Row, kind: string, refTable: string | null, rule?: { onUpdate: string | null; onDelete: string | null }) => {
      const t = tables.get(key(r.schema_name, r.table_name));
      if (!t) return;
      const gk = `${key(r.schema_name, r.table_name)}\u0000${text(r.constraint_name)}`;
      let g = groups.get(gk);
      if (!g) groups.set(gk, (g = { t, name: String(r.constraint_name ?? ''), kind, cols: [], refSchema: text(r.ref_schema), refTable, refCols: [], rule }));
      g.cols.push(String(r.column_name ?? ''));
      if (r.ref_column !== undefined && r.ref_column !== null) g.refCols.push(String(r.ref_column));
    };
    if (flavour === 'sqlserver') {
      for (const r of parts.keys.rows) add(r, String(r.constraint_type), null);
      for (const r of parts.references.rows) add(r, 'FOREIGN KEY', text(r.ref_table), { onUpdate: text(r.on_update), onDelete: text(r.on_delete) });
    } else {
      for (const r of parts.keys.rows) {
        const ref = text(r.ref_table);
        const kind = ref ? 'FOREIGN KEY' : r.constraint_name === 'PRIMARY' ? 'PRIMARY KEY' : 'UNIQUE';
        add(r, kind, ref, ref ? rules.get(`${text(r.table_name)}\u0000${text(r.constraint_name)}`) : undefined);
      }
    }
    for (const g of groups.values()) {
      if (g.kind === 'PRIMARY KEY') g.t.primaryKey = { name: g.name, columns: g.cols };
      else if (g.kind === 'FOREIGN KEY' && g.refTable)
        g.t.foreignKeys!.push({
          name: g.name,
          columns: g.cols,
          refSchema: g.refSchema,
          refTable: g.refTable,
          refColumns: g.refCols,
          // SQL Server says NO_ACTION, SET_NULL
          onUpdate: g.rule?.onUpdate?.replace(/_/g, ' ') ?? null,
          onDelete: g.rule?.onDelete?.replace(/_/g, ' ') ?? null,
        });
    }
    const idx = new Map<string, { t: TableInput; name: string; cols: string[]; unique: boolean; primary: boolean; type: string }>();
    for (const r of parts.indexes.rows) {
      const t = tables.get(key(r.schema_name, r.table_name));
      if (!t || r.column_name === null || r.column_name === undefined) continue;
      const ik = `${key(r.schema_name, r.table_name)}\u0000${text(r.index_name)}`;
      let x = idx.get(ik);
      const name = String(r.index_name ?? '');
      const unique = flavour === 'sqlserver' ? yes(r.is_unique) : !yes(r.non_unique);
      const primary = flavour === 'sqlserver' ? yes(r.is_primary) : name === 'PRIMARY';
      if (!x) idx.set(ik, (x = { t, name, cols: [], unique, primary, type: String(r.index_type ?? '') }));
      x.cols.push(String(r.column_name));
    }
    for (const x of idx.values()) x.t.indexes!.push({ name: x.name, columns: x.cols, unique: x.unique, primary: x.primary, definition: null });
  }
  const truncated = Object.values(parts).some((p) => p.truncated);
  return buildDoc({
    dialect: flavour === 'mariadb' || flavour === 'mysql' ? 'mysql' : flavour,
    product: flavour === 'postgresql' ? 'PostgreSQL' : flavour === 'mariadb' ? 'MariaDB' : flavour === 'mysql' ? 'MySQL' : 'SQL Server',
    serverVersion: ctx.version || null,
    database: ctx.database,
    tables: [...tables.values()],
    truncated,
  });
}

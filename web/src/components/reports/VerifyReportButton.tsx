import { useState } from 'react';
import { Alert, Anchor, Button, FileButton, Modal, Stack, Table, Text } from '@mantine/core';
import { Link } from 'react-router-dom';
import { IconFileSearch } from '@tabler/icons-react';
import type { ReportVerification } from '@sm/shared';
import { api, notifyError } from '../../api';
import { fmtDate } from '../../format';

/** Checks an archived (possibly signed) PDF against the report.generated entries of the audit log. */
export function VerifyReportButton() {
  const [busy, setBusy] = useState(false);
  const [result, setResult] = useState<{ name: string; v: ReportVerification } | null>(null);
  const check = async (file: File | null) => {
    if (!file) return;
    setBusy(true);
    try {
      const form = new FormData();
      form.append('file', file, file.name);
      setResult({ name: file.name, v: await api<ReportVerification>('POST', '/reports/verify', form) });
    } catch (e) {
      notifyError(e, 'Verification failed');
    } finally {
      setBusy(false);
    }
  };
  const v = result?.v;
  return (
    <>
      <FileButton onChange={check} accept="application/pdf">
        {(props) => (
          <Button {...props} size="xs" variant="light" leftSection={<IconFileSearch size={14} />} loading={busy}>
            Verify PDF report
          </Button>
        )}
      </FileButton>
      <Modal opened={!!result} onClose={() => setResult(null)} title="PDF report verification" size="lg">
        {v && (
          <Stack>
            {v.match === 'exact' && (
              <Alert color="green" title="Authentic and unchanged">
                This file is exactly the report generated by this installation. Its SHA-256 is recorded in the audit log.
              </Alert>
            )}
            {v.match === 'signed-copy' && (
              <Alert color="green" title="Authentic report with added signatures">
                The beginning of this file is exactly the generated report; data was appended afterwards, typically digital signatures. Check the signatures in your
                PDF reader.
              </Alert>
            )}
            {v.match === 'unknown' && (
              <Alert color="red" title="Not recognized">
                No report with this content was generated by this installation (or you may not view it). The file may have been changed.
              </Alert>
            )}
            <Table fz="sm" withRowBorders={false}>
              <Table.Tbody>
                <Table.Tr>
                  <Table.Td c="dimmed">File</Table.Td>
                  <Table.Td>{result!.name}</Table.Td>
                </Table.Tr>
                <Table.Tr>
                  <Table.Td c="dimmed">SHA-256 of the file</Table.Td>
                  <Table.Td className="mono" style={{ wordBreak: 'break-all' }}>
                    {v.sha256}
                  </Table.Td>
                </Table.Tr>
                {v.report && (
                  <>
                    <Table.Tr>
                      <Table.Td c="dimmed">Report</Table.Td>
                      <Table.Td>
                        <span className="mono">{v.report.id}</span> {v.report.filename ? `(${v.report.filename})` : ''}
                      </Table.Td>
                    </Table.Tr>
                    {v.report.runId && (
                      <Table.Tr>
                        <Table.Td c="dimmed">Run</Table.Td>
                        <Table.Td>
                          {v.report.stored ? (
                            <Anchor component={Link} to={`/runs/${v.report.runId}`} className="mono" size="sm">
                              {v.report.runId}
                            </Anchor>
                          ) : (
                            <span className="mono">{v.report.runId}</span>
                          )}
                        </Table.Td>
                      </Table.Tr>
                    )}
                    <Table.Tr>
                      <Table.Td c="dimmed">Generated</Table.Td>
                      <Table.Td>
                        {fmtDate(v.report.generatedAt)} by {v.report.generatedBy} · audit entry #{v.report.auditSeq}
                      </Table.Td>
                    </Table.Tr>
                    <Table.Tr>
                      <Table.Td c="dimmed">Recorded SHA-256</Table.Td>
                      <Table.Td className="mono" style={{ wordBreak: 'break-all' }}>
                        {v.report.sha256}
                      </Table.Td>
                    </Table.Tr>
                    {!v.report.stored && (
                      <Table.Tr>
                        <Table.Td c="dimmed">Archive</Table.Td>
                        <Table.Td>The stored copy was removed by data retention; the audit log still proves the content.</Table.Td>
                      </Table.Tr>
                    )}
                  </>
                )}
              </Table.Tbody>
            </Table>
            {v.auditChain && (
              <Alert color={v.auditChain.ok ? 'green' : 'red'} variant="light" p="xs">
                <Text size="sm">Audit chain: {v.auditChain.message}</Text>
              </Alert>
            )}
          </Stack>
        )}
      </Modal>
    </>
  );
}
